package cn.localvault.app.ui.settings

/**
 * 自动填充设置页的内核：四档可用性、那一行开关长什么样、以及
 * 「它为什么有时候不出现」那份清单。
 *
 * **整个文件没有一行 `android.*`，也没有一行 Compose。**
 * 同 [SettingsModel] / `QuickUnlockModel` / `PinSetupModel` 的分工：
 * 碰平台的那一侧只剩一个 `when`（[AutofillAvailability]），
 * 「这句话是不是真的」全在这儿，能在纯 JVM 上钉死。
 *
 * ── 这一页存在的理由，和别的设置页不一样 ──
 *
 * 别的设置页是「让用户改一个我们说了算的值」。这一页管的东西**我们说了不算**：
 * 是不是默认填充服务，由系统那张列表决定；我们既不能自己开，也不能自己关
 * （见 [Row] 上那段）。所以这一页真正的产出不是那个开关，而是**交代**——
 * M4 一路走下来，`FillPlan` / `DomainMatch` / `BrowserTrust` 里那些
 * 「刻意不填」的决定，在用户那边全都长同一个样子：**什么都没弹出来**。
 * 一个功能坏了和一个功能在克制，从屏幕上看不出区别，
 * 那这份克制对用户来说就等于坏了。[WHY_NOT_SHOWING] 是把这个区别说出来的地方。
 */
object AutofillSettingsModel {

    /* ══════════════════════ 四档可用性 ══════════════════════ */

    /**
     * 这台设备此刻的状态。**四档，不是一个布尔值。**
     *
     * 中间那两档（[NoService] / [OtherService]）在屏幕上都表现为「开关是关的」，
     * 但它们对用户的意义完全不同，点下去会发生的事也完全不同——
     * 一个是从无到有，一个是**把他现在用的那个密码管理器顶下去**。
     * 并成一档的后果是后一种情况下用户点了开关，
     * 冷不丁被系统问「确定要替换掉 XX 吗」，而我们这边一个字都没提醒过。
     */
    enum class Availability {

        /** 这台设备根本没有自动填充框架（个别精简 ROM、部分定制系统）。 */
        Unsupported,

        /** 支持，但系统里一个填充服务都没设。 */
        NoService,

        /** 系统里设的是**别的**应用。 */
        OtherService,

        /** 设的就是本应用。 */
        Ours,
    }

    /* ══════════════════════ 那一行开关 ══════════════════════ */

    /**
     * 点这一行会去干什么。
     *
     * 只有两个真动作，**而且两个都是「跳到系统里去」**——这一页自己
     * 什么都改不了。见 [Row] 上那段。
     */
    enum class Action {

        /** 跳到系统那张「选择自动填充服务」的确认屏，本应用已选中。 */
        RequestSetService,

        /** 跳到系统设置总页，让用户自己去关（或换成别的）。 */
        OpenSystemSettings,

        /** 不跳。这台设备上没有可去的地方。 */
        None,
    }

    /**
     * 开关那一行的全部内容。
     *
     * ── 为什么 [checked] 为 true 时开关**仍然能点** ──
     *
     * 因为往回拨这条路，Android 没给应用。
     * `AutofillManager` 上没有任何一个方法能让一个应用把自己从
     * 「默认填充服务」上撤下来——`disableAutofillServices()` 管的是
     * 另一件事（让本应用**自己的界面**不被别的填充服务填），
     * 名字长得像，做的事正好反过来。
     *
     * 于是这里有两个选择：把开关画成灰的（老实但难用，用户会以为关不掉），
     * 或者让它能点、点下去跳到系统那张列表（[Action.OpenSystemSettings]）。
     * 选了后者，**但副标题里必须写清楚这一下不会当场关掉什么**——
     * 一个拨过去自己会弹回来的开关，比一个灰着的开关更让人生气。
     * 这就是决策(61)（不能点的控件必须自己解释为什么）在一个
     * 「能点但不是你想的那样」的控件上的变体。
     */
    data class Row(
        val subtitle: String,
        val checked: Boolean,
        val enabled: Boolean,
        /** 副标题之外还要多说的那一句。没有话说时是 null（同 [SettingsModel.autoLockNote]）。 */
        val note: String?,
        val action: Action,
        /** 行下面那个次按钮的字。没有按钮时是 null。 */
        val buttonText: String?,
        /**
         * [note] 摆在开关**旁边**时的样子：一行，只留那句非看不可的。
         *
         * ── 为什么要有两份 ──
         *
         * 初版把 [note] 整段平铺在开关下面，结果是这一格里说明的高度是开关的三四倍，
         * 一屏扫下来最显眼的东西是一堆灰字，那个唯一能动的控件反而像个附件。
         * 但这几段又都删不得（「系统同时只认一个」那句删掉，用户会不知道
         * 自己刚把另一个密码管理器顶掉了）。
         *
         * 于是拆成两份：这一份跟着控件走，[note] 收进「详细说明」弹窗，一字不删。
         * 两份都由这个文件出，是为了「同一件事的长短两种说法」能在同一个用例里比对着钉住——
         * 短的那份漏掉了关键词，测试会当场发现。
         */
        val noteShort: String? = null,
    )

    fun row(availability: Availability): Row = when (availability) {

        Availability.Unsupported -> Row(
            subtitle = "这台设备上没有自动填充",
            checked = false,
            // 唯一一档真的灰掉。灰掉就必须解释（决策(61)），note 在下面。
            enabled = false,
            note = "自动填充是系统提供的能力，这台设备的系统里没有它。" +
                "保险库本身照常用——复制粘贴走的是另一条路，不受影响。",
            action = Action.None,
            buttonText = null,
            noteShort = "这台设备的系统里没有自动填充。保险库照常用。",
        )

        Availability.NoService -> Row(
            subtitle = "还没设为默认填充服务",
            checked = false,
            enabled = true,
            // 这一档不用多说什么：点一下，系统问一句，就完了。
            note = null,
            action = Action.RequestSetService,
            buttonText = "去系统里设为默认",
            // 这一档不用多说什么，短版也一样是空的。
            noteShort = null,
        )

        Availability.OtherService -> Row(
            subtitle = "现在用的是别的填充服务",
            checked = false,
            enabled = true,
            /*
             * 这一句是这一整页最要紧的一句话。
             *
             * 系统同时只认一个填充服务。用户此刻多半正在用另一个密码管理器，
             * 而他点这个开关时想的是「多开一个」，不是「把那个换掉」。
             * 不说这句话的后果不是「他被吓一跳」——是他真的换掉了，
             * 然后哪天在某个网站上发现存在**那一个**里的密码不出来了，
             * 而他完全想不起来是这一下造成的。
             *
             * 「不会动那个应用里的数据」也得写：换掉服务和删掉数据是两件事，
             * 但在用户脑子里它们离得很近，不写清楚会拦住一部分本该敢试的人。
             */
            note = "系统同时只认一个。设成本应用之后，原来那个就不再弹出填充条了" +
                "——它里面存的东西一个都不会动，随时可以换回去。",
            action = Action.RequestSetService,
            buttonText = "换成本应用",
            // 短到一行，但「只认一个」和「不会动数据」两个意思一个都不能少——
            // 前者是他即将造成的后果，后者是拦住他不敢试的那个误会。
            noteShort = "系统同时只认一个：换过来之后原来那个不再弹填充条，但它里面的东西一个都不会动。",
        )

        Availability.Ours -> Row(
            subtitle = "已经是默认填充服务",
            checked = true,
            // 能点，但点下去是跳出去，不是当场关掉。理由见 Row 上那段。
            enabled = true,
            note = "要关掉的话得去系统设置里换成别的、或者选「无」——" +
                "应用没办法把自己撤下来，这一下只能把你送到那张列表。",
            action = Action.OpenSystemSettings,
            buttonText = "去系统设置里更换",
            noteShort = "应用没办法把自己撤下来，这一下只能把你送到系统那张列表。",
        )
    }

    /* ══════════════════════ 页首那段 ══════════════════════ */

    /**
     * 这一页顶上那句。
     *
     * 只讲**用户会看到什么**，不讲我们做了什么。
     * 「点了输入框，上面冒出一条」是他能对得上的现象；
     * 「解析 AssistStructure 并返回 FillResponse」是我们的事，与他无关。
     */
    const val INTRO: String =
        "设为默认之后，在别的应用或网页里点进账号、密码框，" +
            "键盘上方会多出一条，点一下就把这个保险库里的对应条目填进去。"

    /**
     * 页顶那句的**短版**：只留现象，不带「这个保险库里的对应条目」那半句。
     *
     * 那半句不是废话，但它回答的是「填的是哪一条」，而一个还没开这个功能的人
     * 此刻要判断的只有「开了之后我会看到什么」。完整那段在详细说明的第一段里。
     */
    const val INTRO_SHORT: String =
        "设为默认之后，在别的应用或网页里点账号、密码框，键盘上方会多出一条，点一下就填。"

    /** 页顶那个「详细说明」弹窗的标题。 */
    const val INTRO_DETAIL_TITLE: String = "自动填充是怎么工作的"

    /**
     * 页首那段之后的三条底线。
     *
     * 和关于页 [SettingsModel.AUTOFILL_NOTE] 说的是同一件事，
     * 但**这里不重复那一份**：那一份是讲给「正在评估这个应用值不值得信」的人听的
     * （所以它挨着权限清单），这一份是讲给「已经在用、想弄明白刚才那一下怎么回事」的人听的。
     * 两份都短，各自完整，谁都不必先读另一份。
     */
    val LIMITS: List<String> = listOf(
        "填充条上永远不显示密码，只有条目名称和账号——那块浮层是系统画的。",
        "库锁着的时候只出现一条「先解锁」，连这个网站存了几条都数不出来。",
        "新密码框一律留空。要设新密码请用生成器，我们不拿旧密码去填新密码那一栏。",
    )

    /* ══════════════════════ 「请勿填充」声明那一项 ══════════════════════ */

    /**
     * 这一项的行名。
     *
     * 刻意写成**正面**的说法（「尊重……」）而不是「忽略应用的请勿填充声明」：
     * 一个默认关着的开关，行名应该描述**打开之后会发生什么**。写成「忽略……」
     * 的话，默认状态（关）读起来是「不忽略」＝「尊重」，而实际行为正好相反，
     * 这是这一页最容易被读反的一个地方。
     */
    const val OPT_OUT_TITLE: String = "尊重应用的「请勿填充」声明"

    /**
     * 副标题 + 说明。两档各写各的，不做「已开启 / 未开启」二选一（同 [row]）。
     *
     * [noteShort] 是 [note] 摆在开关旁边时的样子，理由见 [Row.noteShort]：
     * 这两档的完整说明各有三四行，两档加起来就是这一格里最高的东西，
     * 而它管的只是一个开关。短的跟着控件走，长的进弹窗，一字不删。
     */
    data class OptOutRow(
        val subtitle: String,
        val note: String,
        val noteShort: String = note,
    )

    /**
     * [respected] 就是设置里那个值：true = 听应用的。
     *
     * ── 两档的说明为什么都得写满 ──
     *
     * 因为**两个方向都有真实代价**，而它们落在不同的人身上。关着的时候，
     * 我们在做一件应用作者明确表示不希望的事——用户有权知道这件事正在发生，
     * 而不是某天从别处听说。开着的时候，一批应用会彻底填不了，
     * 而那个现象和「这个功能坏了」在屏幕上一模一样（这一页存在的理由，见文件头）。
     *
     * 只写一档的后果是另一档变成暗雷：用户拨过去，过两周遇到症状，
     * 完全想不起来是这一下造成的。
     */
    fun optOutRow(respected: Boolean): OptOutRow = if (respected) OptOutRow(
        subtitle = "标了的输入框一律不填",
        note = "打开之后，凡是标了这句话的框都不再出现填充条——包括一些明明是" +
            "账号密码框的。有些应用（尤其是接了通用登录组件的那批）会因此完全填不了，" +
            "只能复制粘贴。",
        // 开着这一档最容易被当成 bug，短版必须把那个症状原样带出来。
        noteShort = "有些应用会因此完全填不了，只能复制粘贴。",
    ) else OptOutRow(
        subtitle = "认得出的账号密码框照常填",
        note = "有些应用会在自己的账号、密码框上标一句「不要自动填充」。关着的时候" +
            "我们不听那一句：你已经在系统里把填充服务选成了本应用，那是你的决定，" +
            "应用作者的偏好压不过它。填充仍然要你自己点一下才发生。",
        noteShort = "有些应用会在账号密码框上标「不要自动填充」，关着的时候我们不听那一句。",
    )

    /* ══════════════════════ 为什么有时候不出现 ══════════════════════ */

    /**
     * 一条「你看到的」对上一条「为什么」。
     *
     * 分成两段而不是写成一段话，是因为用户是**带着症状来的**：
     * 他记得的是「在某某 App 里没弹出来」，不是「域名归属判定为 NoEvidence」。
     * [symptom] 是给他找位置用的，找到了才会去读 [why]。
     * 一整段连排的解释里，他得逐句读到第四句才知道哪句是说他的。
     */
    data class Reason(val symptom: String, val why: String)

    /**
     * 「它为什么有时候不出现」。
     *
     * ── 这份清单为什么值得单独写 ──
     *
     * 因为 M4 里那些克制的决定，在屏幕上**全都长成同一个样子：什么都没弹出来**。
     * 认不出输入框是这个样子，网站对不上是这个样子，
     * 浏览器不在名单里也是这个样子——而后两种是我们**故意**不填的。
     * 用户没有任何办法把「这个功能坏了」和「这个功能在保护我」分开，
     * 除非有人告诉他。不告诉他的后果不是他生气，是他把这些克制当成 bug，
     * 换一个「什么都肯填」的管理器——那正是 AutoSpill 那条路上的人想要的。
     *
     * ── 顺序是有讲究的 ──
     *
     * 按**发生的概率**排，不按技术上的严重程度排。绝大多数人来翻这一页
     * 是因为第一条或第二条（没设默认 / 库锁着），而那两条一句话就能自己解决。
     * 把「Digital Asset Links 要联网所以我们查不了」摆在第一位是写给自己看的。
     */
