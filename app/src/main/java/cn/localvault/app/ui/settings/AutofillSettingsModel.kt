            symptom = "点了输入框，什么都没冒出来",
            why = "多半是还没在系统里设为默认填充服务。没设的时候，" +
                "系统根本不会来问我们，我们也就不知道你正在哪儿输东西。",
        ),
        Reason(
            symptom = "冒出来了，但只有一条「先解锁」",
            why = "保险库锁着。锁着的时候库文件是一堆密文，" +
                "连这个网站存了几条都数不出来——不是不肯说，是算不出来。" +
                "点那一条解锁完，系统会自己再问一次，填充条就出来了。",
        ),
        Reason(
            symptom = "这一屏明明有账号密码框，还是没有",
            why = "有些应用的输入框没有任何标记（没有 autofill 提示、没有 HTML 类型、" +
                "输入类型也是普通文本）。这种时候我们宁可什么都不猜——" +
                "猜错的代价是把密码填进一个搜索框，而那一下是收不回来的。",
        ),
        Reason(
            symptom = "在某个 App 里，可这条我存的是它的网址",
            why = "一个应用和一个网站是不是同一家，正规的查法是去那个域名上读一份声明文件，" +
                "而那要联网。这个应用连网络权限都没有，所以查不了，也不打算为它破例。" +
                "于是不自动填，但你可以点填充条最后那条「在保险库里搜索」自己挑一条——" +
