package cn.localvault.app.ui.unlock

/**
 * 「我忘了主密码，想从头开始」这件事的内核。
 *
 * **整个文件没有一行 `android.*`，也没有一行 Compose。**
 * 和 `DeleteVaultModel` / `SettingsModel` / `QuickUnlockModel` 同一个套路。
 *
 * ── 这一页是解锁相位唯一的出口 ──
 *
 * 解锁那张图（决策⑪ 的第二张）到现在为止只有一个出口：输对主密码。
 * 输不对的人无路可走——PIN 和指纹都开不了一个他说不出口令的库，
 * 而删除保险库那一页**刻意**没挂在这张图上（决策(124)）。
 * 于是「我确实想不起来了，我想把这台手机上的这一份清掉重新开始」
 * 这条真实存在的路，一直只能去系统设置里绕。这一页把它补上。
 *
 * ── 为什么不能直接把删除页挂过来 ──
 *
 * 因为那一页的门槛是**主密码**（决策(119)）：它要证明「坐在这儿的是本人」。
 * 而这一页面对的恰恰是说不出主密码的人——把删除页挂到解锁相位上，
 * 那个密码框会变成一道谁都过不去的门，页面等于不存在；
 * 把密码框去掉，它就变成一个人人可按的「清空这台手机上的保险库」按钮，
 * 也就是决策⑦ 明令不做的那个拒绝服务漏洞的手动版。两条都不行。
 *
 * ── 那门槛该怎么设：标尺是系统的「清除应用数据」 ──
 *
 * 先承认一件事：**这一页拦不住一个铁了心要毁掉这个库的人。**
 * 拿到这台手机的人本来就可以去「应用信息 → 存储 → 清除数据」，
 * 一路点下去，效果一模一样，那条路不归我们管，我们也拦不住。
 *
 * 所以这一页的门槛不是拿来防攻击的（防不住），它有一把很具体的尺子：
 *
 *   **不比系统那条路更难，也绝不比它更容易。**
 *
 * 更难没有意义——真想毁数据的人会走系统那条，我们多设的门只折腾本人。
 * 更容易则是我们自己的问题：那等于在一个人人可达的界面上，
 * 提供一个比系统还顺手的毁数据入口，决策⑦ 说的正是这个。
 * 系统那条路要「翻进应用信息 → 找到存储 → 点清除数据 → 再确认一次」，
 * 所以这一页给两道：**抄写一句话**（[PHRASE]）和**按住三秒**（[HOLD_MILLIS]）。
 *
 * ── 为什么这里上两道门，删除页却只上一道 ──
 *
 * 决策(119) 拒绝在主密码之外再加抄写，理由是「抄写在主密码之外不新增任何保护，
 * 只新增一次仪式」。那条理由在这一页不成立：这里**根本没有身份证明**，
 * 两道门不是「强的那道之外再添一道弱的」，是全部家当，而且各拦各的——
 * 抄写拦的是没读就一路点主按钮的惯性，按住拦的是刚打完字的手指顺势再点一下。
 *
 * ── 这一页什么元信息都不显示 ──
 *
 * 没有条目数、没有上次改动时间、没有库文件大小。
 * 删除页上摆了一整屏这样的事实（`DeleteVaultModel.facts`），这一页一条都没有，
 * 不是偷懒：**库是锁着的，这些东西读不到，也不该读。**
 * 解锁页那一屏刻意什么都不显示就是这个道理（捡到手机的人不需要打开保险库，
 * 看到「37 条 · 2 分钟前更新」就已经知道这台设备值得带走），
 * 而这一页和解锁页是同一张图上的同一种可达性。
 *
 * 代价是用户在这儿做决定时，最想知道的那两件事我们一件都答不上来。
 * 所以照决策(125) 的办法办：不替他判断，把问题还给他（[QUESTIONS]）。
 *
 * ── 这一页不许出现的话 ──
 *
 * 「找回主密码」「破解」「联系客服」「稍后重试」——一句安慰会让用户
 * 一直等一个永远不会来的救援，而不是趁早去翻那份他其实存过的备份文件。
 * 还有「粉碎」「彻底销毁」那一套，理由同 `DeleteVaultModel.ERASURE_NOTE`（决策⑧）。
 */
object ResetVaultModel {

    /* ══════════════════════ 这一页是干什么的 ══════════════════════ */

    const val TITLE: String = "清空重来"

    /**
     * 副标题。第一句就把这一页**不能**做的事说掉。
     *
     * 走到这儿的人多半是抱着一线希望点进来的（「说不定有别的办法」），
     * 让他在第一行就看清这不是找回入口，比让他读到第三段才发现要好——
     * 后者会让他觉得被绕了一圈。
     */
    const val LEAD: String =
        "这一步会删掉这台设备上的保险库，然后回到新建保险库的界面。" +
            "它不需要主密码，也正因为如此，它帮不了你把里面的东西拿回来。"

    /**
     * [LEAD] 的短版（v4）。
     *
     * 两句话的落点一个不动：**会删掉**，以及**帮不了你拿回来**。
     * 「不需要主密码，也正因为如此」是这两件事之间的因果，进弹窗——
     * 一个抱着侥幸点进来的人，前两行要读到的是结论，不是推导过程。
     */
    const val LEAD_SHORT: String =
        "这一步会删掉这台设备上的保险库，回到新建界面。它帮不了你把里面的东西拿回来。"

    /* ══════════════════════ 先把实话说完 ══════════════════════ */

    /**
     * 为什么没有找回通道。
     *
     * 这句话和解锁页那个「忘记主密码了？」弹窗说的是同一件事，
     * 但那里是一句劝阻（「我再想想」），这里是一个前提——
     * 用户已经想过了，现在需要知道的是这个前提改不了。
     */
    const val NO_RECOVERY: String =
        "主密码没有找回通道。它没有在任何地方留过副本，我们这边也没有，" +
            "所以没有人能绕过它打开这个库——包括我们自己。"

    /**
     * 唯一的那条生路。**两样东西缺一不可**，这是最容易被误会的地方：
     * 很多人以为「我有备份文件」就等于安全，而那份文件认的是导出当时的主密码
     * （中间改过的话就是旧的那个，决策(114)）。
     */
    const val BACKUP_IS_THE_ONLY_WAY: String =
        "能把内容找回来的只有一样东西：你导出过的 .lvault 备份文件，" +
            "外加那份备份当时对应的主密码。两样缺一个，都打不开。"

    /**
     * [NO_RECOVERY] 和 [BACKUP_IS_THE_ONLY_WAY] 合起来的短版（v4）。
     *
     * 这两段原来各占三行，加起来是第一屏的一大半。但它们要传达的其实只有两件事：
     * **没有找回通道**，以及**只有备份 + 当时那个主密码能拿回内容**。
     * 两件都留在外面——这一页的排版顺序（坏消息先说完）就是为它们排的，
     * 收进弹窗等于把这一页的存在理由收进弹窗。
     *
     * 收掉的是论据：为什么没有后门（副本没在任何地方留过、我们这边也没有）、
     * 以及「两样缺一个都打不开」那句强调。它们在 [ExplainBlock] 里一字不删。
     */
    const val NO_RECOVERY_SHORT: String =
        "主密码没有找回通道。能拿回内容的只有你导出的 .lvault 备份和当时的主密码。"

    /** 上面那句「详细说明」弹窗的标题。 */
    const val NO_RECOVERY_TITLE: String = "为什么没有别的办法"

    /**
     * 我们答不上来、只能还给用户的两个问题（决策(125) 的办法）。
     *
     * 用问句而不是判断句，是因为答案只有他知道：文件还在不在那个网盘里、
     * U 盘有没有被格式化过、那份备份的口令他记不记得。
     * 我们连库里有多少条都读不到，更没有立场替他下结论。
     */
    val QUESTIONS: List<String> = listOf(
        "你导出过 .lvault 备份文件吗？它现在在哪儿？",
        "那份备份对应的主密码，你还记得吗？（中间改过主密码的话，它认的是旧的那个）",
    )

    /**
     * 为什么这一页说不出「你要删掉的是 37 条记录」。
     *
     * 这句话是主动交代，不是道歉。用户在删除页上见过那张事实清单，
     * 到这一页突然什么都没有，不解释一下会显得像是没做完。
     */
    const val NO_INVENTORY_NOTE: String =
        "这一页说不出这个库里有多少条、上次改动是什么时候——库还锁着，" +
            "这些东西我们读不到，也不该读。对着一个没解开的保险库能报出条目数的应用，" +
            "才是有问题的那一个。"

    /**
     * [NO_INVENTORY_NOTE] 的短版（v4）。
     *
     * 「读不到，也不该读」这五个字是全句的重心，一个不能少：
     * 前三个字挡住「这应用没做完」的读法，后三个字才是决策(129) 真正要说的。
     * 那句反讽的收尾（能报出条目数的应用才是有问题的那个）进弹窗——
     * 它是说给愿意想一层的人听的，不该占着这一页的第二屏。
     */
    const val NO_INVENTORY_SHORT: String =
        "这一页说不出库里有多少条——库还锁着，这些我们读不到，也不该读。"

    /**
     * 系统那条路。**写出来，但不写在标题上**（同 `DeleteVaultModel.BLOCKED_HINT`）。
     *
     * 写出来是因为它是事实，藏着只会让人以为我们这一页是唯一入口，
     * 从而高估了这个按钮的分量；不放在显眼处是因为没必要教人绕过我们自己的两道门。
     */
    const val SYSTEM_PATH_NOTE: String =
        "同样的事在系统的「应用信息 → 存储 → 清除数据」里也能做，" +
            "任何拿到这台手机的人都能做。这一页不比那条路更难，也刻意不比它更容易。"

    /** [SYSTEM_PATH_NOTE] 的短版（v4）。出口写出来就够了，比较难易进弹窗。 */
    const val SYSTEM_PATH_SHORT: String =
        "同样的事在系统的「应用信息 → 存储 → 清除数据」里也能做。"

    /** 上面那句「详细说明」弹窗的标题。 */
    const val SYSTEM_PATH_TITLE: String = "系统那条路"

    /* ══════════════════════ 会跟着一起没的东西 ══════════════════════ */

    /**
     * 清单。**没绑快捷解锁就不提指纹和 PIN**，同 `DeleteVaultModel.collateral`：
     * 解释一个用户没有的功能，只会让他多读一行、多一分不确定。
     *
     * 第二条特意写出「删掉时同样是一团密文」——这一页的清空全程没有解开过库，
     * 也不需要解开。用户听到「删掉全部条目」时容易以为程序先读了一遍才删的。
     */
    fun collateral(pinEnrolled: Boolean, biometricEnrolled: Boolean): List<String> {
        val out = mutableListOf(
            "保险库文件本身，连同它的上一版备份副本",
            "库里的全部条目和设置——它们从头到尾没有被解开过，删掉时仍然是一团密文",
        )
        val which = when {
            pinEnrolled && biometricEnrolled -> "指纹解锁和 PIN"
            biometricEnrolled -> "指纹解锁"
            pinEnrolled -> "PIN 解锁"
            else -> null
        }
        if (which != null) out += "${which}的绑定，以及安全芯片里对应的那把钥匙"
        /*
         * 退避的账也一起清。这条要写出来，不是因为用户关心，
         * 是因为不清的话下一个库会替上一个库背账——「刚建好的库，
         * 第一次解锁就被告知还要等 15 分钟」，那种界面没人能看懂（决策(120)）。
         * 说出来也不构成绕过：库都没了，没有东西可以爆破。
         */
        out += "解锁的失败计数和等待时间，新建的保险库不会继承上一个的账"
        return out
    }

    /**
     * **不**会跟着没的东西。这一条在删除页上是提醒（别以为清干净了），
     * 在这一页上是全屏唯一的好消息，所以语气反过来。
     */
    const val EXPORTS_NOTE: String =
        "你导出到别处的备份文件不受影响。这一步删的只是这台设备上的这一份，" +
            "网盘、U 盘、别的手机里的副本都还在——清空之后就是拿它们回来的时候。"

    /**
     * [EXPORTS_NOTE] 的短版（v4）。
     *
     * 满屏坏消息里唯一站得住的一件事，两头都得留：**不受影响**，
     * 以及**清空之后就是拿它们回来的时候**——后者是这一页给他的唯一一条前路。
     * 中间那句枚举（网盘、U 盘、别的手机）是举例，进弹窗。
     */
    const val EXPORTS_NOTE_SHORT: String =
        "你导出到别处的备份文件不受影响——清空之后就是拿它们回来的时候。"

    /**
     * 覆写擦除这件事的如实交代（决策⑧）。
     *
     * **它是对 `DeleteVaultModel.ERASURE_NOTE` 的引用，不是抄一份。**
     * 闪存怎么回事只有一个事实，两页各写一份迟早会有一页被改动而另一页没有，
     * 到那时用户在两个界面上会读到两种说法，而这正是这类文案最要命的失败方式。
     */
    const val ERASURE_NOTE: String = cn.localvault.app.ui.settings.DeleteVaultModel.ERASURE_NOTE

    /** 同上，短版也引用删除页那一份（决策(131)：同一件事不许有两份字）。 */
    const val ERASURE_NOTE_SHORT: String =
        cn.localvault.app.ui.settings.DeleteVaultModel.ERASURE_NOTE_SHORT

    /* ══════════════════════ 门槛之一：抄写 ══════════════════════ */

    /**
     * 要抄的那一句。
     *
     * ── 为什么是一句关于用户自己的陈述，而不是「删除保险库」这种口令 ──
     *
     * 抄一个动词短语（「删除保险库」「DELETE」）只是打字，打完了脑子里什么都没留下。
     * 抄这一句不一样：它是一句**关于当事人处境的陈述**，
     * 而这一页最需要拦住的那个人——记得主密码、只是点错了地方的人——
     * 要打的这几个字是假的。人在照抄一句关于自己的假话时会停顿，
     * 这个停顿就是我们要的全部。
     *
     * 顺带一提：屏幕上那句范文**不能做成可选中的文字**。
     * Compose 的 `Text` 默认不可选中，所以现状是对的，但那是默认值凑巧对了，
     * 不是有人决定过——别哪天为了「方便」在外面套一个 `SelectionContainer`，
     * 那等于把这道门改成「长按 → 复制 → 粘贴」。
     */
    const val PHRASE: String = "我没有主密码了"

    const val PHRASE_LABEL: String = "照着抄这一句："

    /**
     * 输入框下面那句话。它把这道门的用意直说出来。
     *
     * 「不告诉用户我们在防什么」是这类设计里最常见的毛病：
     * 用户会把抄写当成一道莫名其妙的手续，学会的是「照着抄就行」，
     * 那这道门就真的只剩仪式了（决策(119) 担心的正是这个）。
     */
    const val PHRASE_HINT: String =
        "这一句不是口令，是一句关于你自己的话。如果你其实记得主密码、只是点错了地方，" +
            "请在这里停下——你要打的这几个字是假的。"

    /**
     * [PHRASE_HINT] 的短版（v4）。
     *
     * 这一句的作用是**截停**，所以短版留的是那道停止线本身，
     * 不是它的修辞（「你要打的这几个字是假的」）。那句进弹窗。
     */
    const val PHRASE_HINT_SHORT: String =
        "这一句不是口令。如果你其实记得主密码、只是点错了地方，请在这里停下。"

    /**
     * 抄写比对前的归一化。
     *
     * 宽容的部分：首尾和中间的空白（中文输入法在候选上屏时常带出空格）、
     * 结尾的句号叹号（有人抄完会习惯性点一个）。
     * 不宽容的部分：错字、少字、多字。那正是这道门要拦的东西。
     *
     * **不做的事**：不忽略大小写（这句话没有拉丁字母）、不做繁简转换
     * （繁体输入法打出的是另一句话，放行等于承认「差不多就行」）、
     * 不去掉中间的标点。
     */
    fun normalize(input: String): String =
        input.filterNot { it.isWhitespace() }.trimEnd('。', '.', '！', '!', '，', ',')

    fun matches(input: String): Boolean = normalize(input) == PHRASE

    /* ══════════════════════ 门槛之二：按住 ══════════════════════ */

    /**
     * 按住不放的时长。
     *
     * ── 为什么抄完之后还要按住 ──
     *
     * 因为抄写结束的那一刻是这一页最危险的一刻：用户刚打完字，
     * 手指停在屏幕下方，输入法收起来的同时按钮跳到手指底下，
     * 而一个刚打完字的人最容易做的下一个动作就是再点一下。
     * 把「点一下」换成「按住三秒」，中途松手就中止，什么都不会发生。
     *
     * 三秒是有上限的仪式：再长（五秒、十秒）就越过了上面那把尺子——
     * 比系统那条路还折腾，而系统那条路本人也走得通。
     */
    const val HOLD_MILLIS: Long = 3000L

    const val BUTTON_IDLE: String = "按住不放，清空这个保险库"

    /**
     * 按住过程中按钮上的字。**要一直告诉用户还剩几秒**，
     * 否则「按住」和「卡死了」在手感上分不出来。
     */
    fun holdLabel(remainingMillis: Long): String {
        val secs = ((remainingMillis + 999L) / 1000L).coerceAtLeast(1L)
        return "继续按住…$secs"
    }

    const val HOLD_HINT: String = "松手就中止，不会有任何事情发生。"

    /**
     * 按钮能不能开始响应长按。
     *
     * 抄错的时候按钮是**灰的**，不是「按了给一句『抄错了』」——
     * 后者会把这道门变成一个可以反复试的谜题，而它本来就不是谜题。
     */
    fun canArm(input: String, busy: Boolean): Boolean = matches(input) && !busy

    /* ══════════════════════ 正在做什么 ══════════════════════ */

    /**
     * 两步的字面。和删除页那三步同口径（那里多一步「正在核对主密码」，
     * 这一页没有口令可核对，所以只有两步）。
     *
     * 这两句话必须出现在屏幕上，哪怕它们只闪一下：用户此刻盯着的是
     * 一个正在删掉他全部密码的程序，一个没有任何字的转圈动画
     * 会让「它到底删到哪一步了」变成事后无法回答的问题。
     */
    const val STEP_PURGING: String = "正在清除指纹 / PIN 的绑定与剪贴板…"
    const val STEP_DELETING: String = "正在删除保险库文件…"

    /* ══════════════════════ 失败了说什么 ══════════════════════ */

    /**
     * 两种失败。
     *
     * 注意这里**没有** `DeleteVaultModel.Failure.WrongPassword` 那一支——
     * 这一页压根没有口令要核对，那正是它存在的理由。
     *
     * 还有一处和删除页反着来：那边每条失败文案都要写出「保险库还在，
     * 数据一条没少」当作安慰，因为那边的用户怕的是「删了一半」；
     * 这一页的用户要的就是删掉，「库还在」对他是坏消息，
     * 所以每条都得跟上一条**还能怎么办**。
     */
    enum class Failure {
        /** 残留清掉了，库文件没删成（权限、正被占用之类） */
        FilesRemain,

        Unknown,
    }

    fun failureMessage(f: Failure): String = when (f) {
        Failure.FilesRemain ->
            "库文件没能删掉，它还在这台设备上。指纹和 PIN 的绑定已经在这一步之前清掉了" +
                "——反正它们也开不了一个你打不开的库。可以再按一次试试；" +
                "还是不行的话，去系统的「应用信息 → 存储 → 清除数据」，那是同一件事。"
        Failure.Unknown ->
            "清空没有完成，保险库还在这台设备上。可以再按一次试试；" +
                "还是不行的话，系统的「应用信息 → 存储 → 清除数据」是通向同一个结果的另一条路。"
    }

    /* ══════════════════════ 解锁页那个弹窗的落点 ══════════════════════ */

    /**
     * 解锁页「忘记主密码了？」那个弹窗上新增的次按钮。
     *
     * ── 为什么是次按钮，不是主按钮 ──
     *
     * 主按钮留给「我再想想」。这个弹窗的常客不是已经死心的人，
     * 是抱着侥幸点开看看的人，而对他来说最好的结果是关掉弹窗再想一会儿。
     * 决策⑮ 已经把次按钮和取消手势拆成两个回调了，所以把清空放在次按钮上是安全的：
     * 点弹窗外面的空白只会关掉弹窗，绝不会走到这里。
     *
     * ── 为什么是「跳到一页」而不是「弹窗上直接删」 ──
     *
     * 弹窗上放不下两道门，也放不下那几段实话。更要紧的是弹窗天生是个
     * 「点两下就过去了」的部件，而这是全 App 第二个不可逆的动作。
     */
    const val DIALOG_SECONDARY: String = "清空这一份，从头开始"

    /**
     * 弹窗上要补的一句。现在那个弹窗说完「只有一条路：用备份恢复」就没有下文了，
     * 而对一个**没有**备份的人来说，那句话读完是死胡同。
     * 这一句给出下一步，同时把它是什么、不是什么讲清楚。
     */
    const val DIALOG_SECONDARY_NOTE: String =
        "如果你连备份也没有，那就只剩清空这台设备上的这一份、从头开始这一条路了。" +
            "它不会让你重新拿到里面的东西。"
}
